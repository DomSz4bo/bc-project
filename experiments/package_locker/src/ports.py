from typing import Protocol, Optional
from src.models import PackageRecord

class DatabasePort(Protocol):
    def query_package_by_code(self, code: str) -> Optional[PackageRecord]: ...
    def flag_locker_error(self, locker_id: str) -> None: ...
    def update_package_status(self, package_id: str, status: str) -> None: ...

class PaymentGatewayPort(Protocol):
    def request_payment(self, amount: float) -> Optional[str]: ...
    def trigger_refund(self, transaction_id: str) -> bool: ...

class LockerControllerPort(Protocol):
    def open_door(self, locker_id: str) -> str: ...