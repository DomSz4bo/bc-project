from typing import Protocol, Optional

class InventoryPort(Protocol):
    def validate_availability(self, product_id: str) -> Optional[float]: ...
    def dispense_product(self, product_id: str) -> bool: ...

class CoinHandlerPort(Protocol):
    def return_coins(self, amount: float) -> None: ...
    def check_change_capacity(self, amount: float) -> bool: ...
    def notify_currency_inserted(self, amount: float) -> None: ...